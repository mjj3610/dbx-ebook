const dictionaries: Record<string, Dict> = { 'zh-CN': zhCN, en }

/** 使用模板替换参数 */
function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    vars[key] === undefined ? match : String(vars[key]),
  )
}

/** 当前语言字典 */
export const currentDict = computed<Dict>(() => dictionaries[settings.reader.locale] ?? zhCN)

/**
 * 取翻译文案
 * @param key 文案键
 * @param vars 插值参数
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[settings.reader.locale] ?? zhCN
  return format(dict[key] ?? zhCN[key] ?? key, vars)
}

